"""
05_lda_strands.py — Topic modeling on abstracts to identify research strands
=============================================================================

Runs Latent Dirichlet Allocation (Blei, Ng, Jordan 2003) on paper
abstracts to discover latent research strands. Each paper is assigned
to its dominant topic; the researcher names each topic based on its
top-weighted terms.

LDA is preferred over keyword clustering because author keywords are
sparse and inconsistent across corpora (OpenAlex lacks them for
humanities; KCI provides them bilingually but at varying granularity).
Abstract text provides a more reliable signal for topic discovery.

Inputs:  _data/all_papers.json, config.yaml (LDA parameters)
Outputs: _data/lda_topics.json, _data/lda_assignments.json,
         _data/strand_names.json (template), updated _data/all_papers.json

Dependencies: scikit-learn, nltk, pyyaml
Run: python 05_lda_strands.py
"""

import json
import re
import yaml
from pathlib import Path
from collections import defaultdict

from sklearn.decomposition import LatentDirichletAllocation
from sklearn.feature_extraction.text import CountVectorizer
import nltk
from nltk.stem import WordNetLemmatizer

# --- Load config ---
config_path = Path(__file__).parent / "config.yaml"
with open(config_path, encoding="utf-8") as f:
    config = yaml.safe_load(f)

_vr = Path(config["vault_root"])
VAULT_ROOT = _vr if _vr.is_absolute() else (Path(__file__).parent / _vr).resolve()
DATA_DIR = VAULT_ROOT / config["paths"]["data"]
LDA_CONFIG = config.get("lda", {})
NUM_TOPICS = LDA_CONFIG.get("num_topics", 10)
NO_BELOW = LDA_CONFIG.get("no_below", 5)
NO_ABOVE = LDA_CONFIG.get("no_above", 0.5)
TOPIC_THRESHOLD = LDA_CONFIG.get("topic_threshold", 0.20)  # multi-tag above this

# --- Stopwords ---
# Loaded from stopwords.json (generated by 05a_stopword_audit.py).
# If stopwords.json doesn't exist, falls back to a minimal hardcoded set.
_stopwords_path = DATA_DIR / "stopwords.json"
if _stopwords_path.exists():
    with open(_stopwords_path, encoding="utf-8") as _f:
        ALL_STOPWORDS = set(json.load(_f)["words"].keys())
else:
    ALL_STOPWORDS = {
        "yeats", "yeat", "poem", "poetry", "poet", "poetic",
        "paper", "study", "article", "research", "analysis", "argue",
        "work", "literary", "literature", "irish", "ireland",
        "william", "butler",
        "예이츠", "시", "시인", "문학", "연구", "논문", "분석",
    }


def preprocess(text: str) -> str:
    """
    Clean and lemmatize abstract text. Returns a single string
    (scikit-learn's CountVectorizer handles tokenization).
    """
    lemmatizer = WordNetLemmatizer()

    text = text.lower()
    # Strip URLs, DOI patterns, and OpenAlex machine-keyword boilerplate
    text = re.sub(r'https?://\S+', '', text)
    text = re.sub(r'doi[:\s]*10\.\S+', '', text)
    text = re.sub(r'these keywords were added by machine.*?learning algorithm improves\.?', '', text, flags=re.DOTALL)
    # Latin script only (3+ chars). Korean is excluded from LDA so that
    # KCI papers model on their English abstracts and distribute across
    # topics on equal footing with anglophone papers. The KCI/angl ratio
    # per topic IS the gap analysis signal — mixing scripts defeats that.
    tokens = re.findall(r'[a-z]{3,}', text)

    tokens = [
        lem for t in tokens
        if (lem := lemmatizer.lemmatize(t)) not in ALL_STOPWORDS
    ]

    return " ".join(tokens)


def run_lda():
    # Load data
    merged_path = DATA_DIR / "all_papers.json"
    with open(merged_path, encoding="utf-8") as f:
        all_papers = json.load(f)

    print(f"  Loaded {len(all_papers)} papers")

    # Exclude boilerplate abstracts if audit has been run
    boilerplate_path = DATA_DIR / "boilerplate_flagged.json"
    boilerplate_indices = set()
    if boilerplate_path.exists():
        with open(boilerplate_path, encoding="utf-8") as f:
            flagged = json.load(f)
        boilerplate_indices = {item["index"] for item in flagged}
        print(f"  Excluding {len(boilerplate_indices)} boilerplate abstracts (from 05a audit)")

    # Preprocess abstracts
    print("  Preprocessing abstracts...")
    processed_docs = []
    paper_indices = []

    for i, paper in enumerate(all_papers):
        if i in boilerplate_indices:
            continue

        # For bilingual papers, use English abstract only (last element)
        abstract_parts = paper.get("abstracts", [paper.get("abstract", "")])
        if len(abstract_parts) > 1:
            text = abstract_parts[-1]
        else:
            text = abstract_parts[0] if abstract_parts else paper.get("abstract", "")

        if len(text.strip()) < 50:
            continue

        cleaned = preprocess(text)
        if len(cleaned.split()) >= 5:
            processed_docs.append(cleaned)
            paper_indices.append(i)

    print(f"  Usable abstracts: {len(processed_docs)} / {len(all_papers)}")

    vectorizer = CountVectorizer(
        min_df=NO_BELOW,
        max_df=NO_ABOVE,
        max_features=10000,
    )

    doc_term_matrix = vectorizer.fit_transform(processed_docs)
    feature_names = vectorizer.get_feature_names_out()
    print(f"  Vocabulary size: {len(feature_names)}")

    print(f"\n  Running LDA with {NUM_TOPICS} topics...")

    lda = LatentDirichletAllocation(
        n_components=NUM_TOPICS,
        max_iter=25,
        learning_method="batch",  # our corpus is small enough for batch
        random_state=42,
        n_jobs=-1,
    )

    doc_topic_matrix = lda.fit_transform(doc_term_matrix)

    # Extract top words per topic
    print("\n  === TOPICS (name these!) ===\n")
    topic_words = {}
    for topic_id in range(NUM_TOPICS):
        # lda.components_[topic_id] = word weights for this topic
        top_word_indices = lda.components_[topic_id].argsort()[::-1][:15]
        top_words = [(feature_names[i], round(float(lda.components_[topic_id][i]), 2))
                     for i in top_word_indices]
        topic_words[topic_id] = [w for w, s in top_words]

        words_str = ", ".join(f"{w} ({s})" for w, s in top_words)
        print(f"  Topic {topic_id}: {words_str}")

    # Perplexity (lower = better fit, but mainly useful for comparing num_topics)
    perplexity = lda.perplexity(doc_term_matrix)
    print(f"\n  Perplexity: {perplexity:.2f} (lower = better fit)")

    # Assign papers to all topics above threshold (multi-tagging)
    print(f"\n  Assigning papers to topics (threshold: {TOPIC_THRESHOLD})...")
    assignments = {}
    topic_counts = defaultdict(lambda: {"total": 0, "KCI": 0, "angl": 0})

    for doc_idx in range(len(processed_docs)):
        paper_idx = paper_indices[doc_idx]
        paper = all_papers[paper_idx]

        topic_probs = doc_topic_matrix[doc_idx]
        assigned_topics = [
            {"topic_id": int(tid), "probability": round(float(topic_probs[tid]), 4)}
            for tid in range(NUM_TOPICS)
            if topic_probs[tid] >= TOPIC_THRESHOLD
        ]
        assigned_topics.sort(key=lambda x: x["probability"], reverse=True)

        title = paper.get("title", "Untitled")
        corpus = paper.get("corpus", "angl")

        assignments[title] = {
            "topics": assigned_topics,
            "corpus": corpus,
        }

        paper["lda_topics"] = [t["topic_id"] for t in assigned_topics]
        paper["lda_topic_probs"] = {t["topic_id"]: t["probability"] for t in assigned_topics}

        for t in assigned_topics:
            topic_counts[t["topic_id"]]["total"] += 1
            topic_counts[t["topic_id"]][corpus] += 1

    multi_count = sum(1 for a in assignments.values() if len(a["topics"]) > 1)
    print(f"  Papers with 2+ strands: {multi_count} / {len(assignments)}")

    # Print per-topic distribution
    print(f"\n  {'Topic':<8} {'Total':>6} {'KCI':>6} {'Angl':>6} {'Top words'}")
    print(f"  {'-'*8} {'-'*6} {'-'*6} {'-'*6} {'-'*40}")
    for tid in range(NUM_TOPICS):
        tc = topic_counts[tid]
        words = ", ".join(topic_words[tid][:5])
        print(f"  {tid:<8} {tc['total']:>6} {tc['KCI']:>6} {tc['angl']:>6} {words}")

    # Save outputs
    topics_path = DATA_DIR / "lda_topics.json"
    with open(topics_path, "w", encoding="utf-8") as f:
        json.dump({
            "num_topics": NUM_TOPICS,
            "perplexity": round(perplexity, 2),
            "topics": {
                str(tid): topic_words[tid] for tid in range(NUM_TOPICS)
            }
        }, f, ensure_ascii=False, indent=2)

    assign_path = DATA_DIR / "lda_assignments.json"
    with open(assign_path, "w", encoding="utf-8") as f:
        json.dump(assignments, f, ensure_ascii=False, indent=2)

    # Updated all_papers with LDA info
    with open(merged_path, "w", encoding="utf-8") as f:
        json.dump(all_papers, f, ensure_ascii=False, indent=2)

    # Strand name template
    names_path = DATA_DIR / "strand_names.json"
    if not names_path.exists():
        template = {str(i): f"Topic {i} — NAME ME" for i in range(NUM_TOPICS)}
        with open(names_path, "w", encoding="utf-8") as f:
            json.dump(template, f, ensure_ascii=False, indent=2)
        print("\n  Created strand_names.json — EDIT THIS to name your strands.")

    print("\n=== Done ===")
    print(f"  Topics saved to: {topics_path}")
    print(f"  Assignments saved to: {assign_path}")
    print("\n  >>> NEXT: Open _data/strand_names.json and name each topic.")
    print("  >>> Then run 06_gap_analysis.py")


if __name__ == "__main__":
    import sys
    import io
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")
    print("=== LDA Topic Modeling ===\n")

    try:
        nltk.data.find("corpora/wordnet")
    except LookupError:
        print("  Downloading NLTK data...")
        nltk.download("wordnet", quiet=True)

    run_lda()
